function detectLang() {
  const saved = store('lang');
  if (saved === 'pt' || saved === 'en') return saved;
  return /^pt\b/i.test(navigator.language || '') ? 'pt' : 'en';
}
let LANG = detectLang();

function i18n(key, params) {
  let s = STRINGS[LANG][key];
  if (s === undefined) s = STRINGS.pt[key] !== undefined ? STRINGS.pt[key] : key;
  if (params) for (const k in params) s = s.split('{' + k + '}').join(params[k]);
  return s;
}

function applyI18n() {
  document.documentElement.lang = LANG === 'pt' ? 'pt-BR' : 'en';
  $('c').setAttribute('aria-label', i18n('aria.canvas'));
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = i18n(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = i18n(el.dataset.i18nHtml);
  updateMenuRecord();
  HUD.motor = null;
  if (!$('settings').hidden) refreshSettings();
  if (GAME.state === 'result') renderResults();
}

function setLang(l) {
  LANG = l;
  store('lang', l);
  applyI18n();
}
